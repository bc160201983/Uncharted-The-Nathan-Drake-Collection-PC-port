#!/usr/bin/env python3
"""PS3 U3 GOTY -> PS4 Collection multiplayer content inventory (maps, characters, taunts).
Reads the staged listings (level lists, file trees, psarc TOCs) and prints Markdown."""
import os, re, sys
from collections import defaultdict, OrderedDict

INV = sys.argv[1] if len(sys.argv) > 1 else \
    '/mnt/user-data/uploads/Uncharted The Nathan Drake Collection - U3 Multiplayer/work/inventory'


def parse_levels(fn):
    L = OrderedDict()
    cur = None
    for line in open(os.path.join(INV, fn)):
        t = line.split()
        if not t:
            continue
        k, v = t[0], (t[1] if len(t) > 1 else '')
        if k == 'level-name':
            cur = v
            L[cur] = defaultdict(list)
            continue
        if cur is not None and v:
            L[cur][k].append(v)
    return L


def toc(fn):
    out = {}
    for line in open(os.path.join(INV, fn)):
        t = line.split()
        if len(t) == 3 and t[0].isdigit():
            out[t[2]] = int(t[1])
    return out


def files(fn):
    out = {}
    for line in open(os.path.join(INV, fn)):
        p, _, s = line.rstrip('\n').partition('\t')
        out[p] = int(s) if s.isdigit() else 0
    return out


p3 = parse_levels('ps3-pak23.txt')
p4 = parse_levels('ps4-pak23.txt')
pak3 = toc('ps3-pak23-psarc.txt')
act3 = toc('ps3-actor33-psarc.txt')
stm3 = toc('ps3-animstream4-psarc.txt')
bin3 = toc('ps3-bin-psarc.txt')
f4 = files('ps4-files.tsv')
pak4 = {os.path.basename(p): s for p, s in f4.items() if p.startswith('./pak23/ps4/')}
act4 = {os.path.basename(p): s for p, s in f4.items() if p.startswith('./actor33/ps4/')}
dc4 = {os.path.basename(p): s for p, s in f4.items() if p.startswith('./dc1/ps4/')}
part4 = {os.path.basename(p): s for p, s in f4.items() if p.startswith('./dc2/part-module/')}
part3 = {os.path.basename(p): s for p, s in bin3.items() if 'part-module' in p}


def pkg_files(pkg):
    """package name -> candidate file names ('-ingame' packages are stored as '-ingame12.pak')"""
    c = [pkg + '.pak']
    if pkg.endswith('-ingame'):
        c.insert(0, pkg + '12.pak')
    return c


def has(table, pkg):
    for c in pkg_files(pkg):
        if c in table:
            return c, table[c]
    return None, 0


# ---------------------------------------------------------------- MP map grouping
MAPS = OrderedDict([
    ('Airstrip (air-multi)', r'^(air-multi|cargo-plane-air-multi|sky-air-multi)'),
    ('Yemen (yemen-multi)', r'^(yemen-multi|yemen-airport-multi|sky-yemen-mp|world-yemen-mp)'),
    ('Chateau (cha-multi)', r'^(cha-multi|sky-chateau-multi)'),
    ('Chateau MP world (chat-*)', r'^(chat-|world-chat-mp)'),
    ('Desert / Village (desert-multi)', r'^(desert-multi|sky-des-multi)'),
    ('Facility (facility-multi)', r'^facility-multi'),
    ('Highrise (highrise-multi)', r'^(highrise-multi|sky-highrise-multi)'),
    ('Museum (museum-multi)', r'^museum-multi'),
    ('Ruins (ruins-multi)', r'^(ruins-multi|sky-ruins-multi)'),
    ('Syria (syria-multi)', r'^syria-multi'),
    ('Sanctuary (san-upper-multi / san-multi)', r'^(san-upper-multi|san-upper-wide-multi|san-multi|sky-san-upper-multi)'),
    ('London Underground (ldn-train-multi)', r'^ldn-train-multi'),
    ('London Downtown / city (ldn-multi, city-multi)', r'^(ldn-multi|city-multi|world-city-mp|world-london-mp)'),
    ('Shipyard / Graveyard (graveyard-*, world-grave-mp)', r'^(graveyard-|world-grave-mp|drydock)'),
    ('Co-op Arenas / Adventure (coop-*, dig-coop, mon-coop, *-adv)',
     r'^(coop-|dig-coop|mon-coop|mon-adv|dig-adv|world-coop-adv|sky-coop|sky-dig-coop|sky-mon-coop|ldn-train-stage-coop)'),
    ('MP common (net, multi-*, world-multiplayer)', r'^(net$|net-|multi-all|multi-menu|world-multiplayer)'),
])


def classify(name):
    for k, rx in MAPS.items():
        if re.search(rx, name):
            return k
    return None


groups = OrderedDict((k, []) for k in MAPS)
for n in p3:
    g = classify(n)
    if g:
        groups[g].append(n)

out = []
w = out.append
w('# U3 multiplayer content inventory: PS3 GOTY (BCES01670) vs PS4 Collection (CUSA02320)\n')
w('Generated by `/home/claude/u3/paktools/mp_inventory.py` from the staged listings in `work/inventory/` '
  '(level lists `pak23.txt`, file trees, psarc TOCs). "pkg" = package file in `pak23` '
  '(`X-ingame` packages are stored as `X-ingame12.pak`), "actor" = `actor33/<name>.pak`, '
  '"pm" = particle module (`dc2/part-module/<name>.bin` on PS4, `bin.psarc` on PS3).\n')
w('**Not evaluated:** sound banks and animstreams for PS4 (no PS4 `sound1/` or animstream '
  'listing was staged; PS4 `bin.psarc`/`core.psarc` TOCs were not staged either, so DC '
  'modules other than the loose `dc1/ps4/*.bin` could not be checked).\n')

# ------------------------------------------------------------- a. maps
w('\n## a. Multiplayer maps\n')
summary = []
all_mp_actors = set()
all_mp_pms = set()
all_mp_banks = set()
for g, levels in groups.items():
    if not levels:
        continue
    lvl_present = sum(1 for n in levels if n in p4)
    pk_total = pk3 = pk4 = 0
    act_need, pm_need, bank_need = set(), set(), set()
    rows = []
    for n in levels:
        d3 = p3[n]
        pk = d3.get('package', [])
        pkrow = []
        for p in pk:
            pk_total += 1
            f3, s3 = has(pak3, p)
            f4_, s4 = has(pak4, p)
            pk3 += bool(f3)
            pk4 += bool(f4_)
            pkrow.append('%s%s' % (p, '' if f4_ else (' ✗' if f3 else ' ✗(PS3 file missing too)')))
        act_need |= set(d3.get('actor', []))
        pm_need |= set(d3.get('particle-module', []))
        bank_need |= set(d3.get('sound-bank', []))
        rows.append('| %s | %s | %s | %d | %d | %s |' % (
            n, 'yes' if n in p4 else '**no**', ', '.join(pkrow) or '-', len(d3.get('actor', [])),
            len(d3.get('particle-module', [])), ', '.join(d3.get('sound-bank', [])) or '-'))
    act_missing = sorted(a for a in act_need if a + '.pak' not in act4)
    pm_missing = sorted(p for p in pm_need if p + '.bin' not in part4)
    all_mp_actors |= act_need
    all_mp_pms |= pm_need
    all_mp_banks |= bank_need
    if lvl_present == len(levels) and pk4 == pk_total and not act_missing:
        status = 'FULL'
    elif lvl_present == 0 and pk4 == 0:
        status = 'ABSENT'
    else:
        status = 'PARTIAL'
    summary.append((g, status, len(levels), lvl_present, pk_total, pk4, len(act_need), len(act_need) - len(act_missing),
                    len(pm_need), len(pm_need) - len(pm_missing)))
    w('\n### %s — %s\n' % (g, status))
    w('Levels %d (PS4 level entries: %d), packages %d (PS3 files %d, PS4 files %d), actors %d '
      '(PS4 has %d), particle modules %d (PS4 has %d), sound banks: %s\n' % (
          len(levels), lvl_present, pk_total, pk3, pk4, len(act_need), len(act_need) - len(act_missing),
          len(pm_need), len(pm_need) - len(pm_missing), ', '.join(sorted(bank_need)) or '-'))
    w('| level | PS4 entry | packages (✗ = no PS4 file) | actors | pms | sound banks |')
    w('|---|---|---|---|---|---|')
    out.extend(rows)
    if act_missing:
        w('\nActors missing on PS4 (%d): %s\n' % (len(act_missing), ', '.join(act_missing)))
    if pm_missing:
        w('\nParticle modules missing on PS4 (%d): %s\n' % (len(pm_missing), ', '.join(pm_missing)))

w('\n### Map summary\n')
w('| map | status | levels (PS4) | packages (PS4 files) | actors (PS4) | particle modules (PS4) |')
w('|---|---|---|---|---|---|')
for s in summary:
    w('| %s | %s | %d (%d) | %d (%d) | %d (%d) | %d (%d) |' % s)

# extra: PS4 MP-ish level entries that exist
mp4 = [n for n in p4 if classify(n)]
w('\nPS4 level entries that match MP/co-op names: %s\n' % (', '.join(mp4) or 'none'))
mppk4 = sorted(f for f in pak4 if re.search(r'multi|-mp|coop|net', f))
w('PS4 `pak23` files with MP/co-op-like names: %s\n' % (', '.join(mppk4) or 'none'))

# ------------------------------------------------------------- b. characters
w('\n## b. Multiplayer characters / skins\n')
mp_act3 = sorted(a[:-4] for a in act3 if a.endswith('.pak') and re.match(r'mp-', a))
present = [a for a in mp_act3 if a + '.pak' in act4]
missing = [a for a in mp_act3 if a + '.pak' not in act4]
w('PS3 `actor33` has %d `mp-*` actors; PS4 has %d of them, %d missing.\n' % (len(mp_act3), len(present), len(missing)))


def family(a):
    m = re.match(r'mp-(hero|chloe|kit|villain|coop)-?(.*)', a)
    return m.group(1) if m else 'other'


fam = defaultdict(lambda: [0, 0])
for a in mp_act3:
    fam[family(a)][0] += 1
    fam[family(a)][1] += a + '.pak' in act4
w('| family | PS3 | on PS4 |')
w('|---|---|---|')
for k, (a, b) in sorted(fam.items()):
    w('| mp-%s-* | %d | %d |' % (k, a, b))
w('\nMissing on PS4 (%d): %s\n' % (len(missing), ', '.join(missing)))
if present:
    w('\nPresent on PS4 (%d): %s\n' % (len(present), ', '.join(present)))

# campaign equivalents: map mp-hero-X-torso -> campaign actor names present on PS4
w('\n### Remastered campaign models that match MP skins\n')
w('Heuristic: for each MP skin key (`mp-hero-<key>-torso/legs`, `mp-chloe-<key>-...`) list PS4 '
  '`actor33` packages whose name contains the key (campaign/remastered models). A match means a '
  'PS4-native character model exists that could replace the PS3 skin; it still needs the MP '
  'skeleton/attachment set-up (see d).\n')
keys = OrderedDict()
for a in mp_act3:
    m = re.match(r'mp-(hero|chloe)-(.+?)-(torso|legs|hair|coop|bones|flesh)$', a) or re.match(r'mp-(hero|chloe)-(.+)$', a)
    if m:
        keys.setdefault(m.group(2), []).append(a)
SYN = {'sullivan': ['sully', 'sullivan'], 'young-sullivan': ['young-sully', 'young-sullivan'],
       'french': ['charlie', 'cutter'], 'cutter': ['cutter', 'charlie'], 'talbot': ['talbot'],
       'flynn': ['flynn'], 'lazarevic': ['lazarevic', 'laz'], 'navarro': ['navarro'], 'eddie': ['eddie'],
       'u2': ['hero-u2', 'drake-u2'], 'london': ['hero-london', 'london'], 'desert': ['hero-desert'],
       'winter': ['winter'], 'ramses': ['ramses'], 'marlowe': ['marlowe'], 'elena': ['elena'],
       'chloe': ['chloe'], 'roman': ['roman'], 'guerro': ['guerro'], 'pirate': ['pirate'],
       'divesuit': ['divesuit', 'dive'], 'schafer': ['schafer'], 'jeff': ['jeff'],
       'bed-leader': ['bedouin-leader', 'bed-leader', 'sheikh', 'salim'], 'rescuer': ['rescuer'],
       'lieutenant': ['lieutenant'], 'dead-agent': ['agent'], 'dead-explorer': ['explorer'],
       'fat': ['fat'], 'subway': ['subway'], 'redshirt': ['redshirt'], 'udf': ['udf'], 'ngp': ['ngp'],
       'skel': ['skel'], 'sol': ['sol-'], 'young-marlowe': ['young-marlowe', 'marlowe']}
camp = sorted(a[:-4] for a in act4 if a.endswith('.pak') and not a.startswith(('mp-', 'anim-')))
w('| MP skin key | PS3 mp actors | PS4 on disc (mp-*) | PS4 campaign candidates |')
w('|---|---|---|---|')
for k, lst in keys.items():
    base = k.split('-')[0] if k not in SYN else k
    terms = SYN.get(k) or SYN.get(base) or [k]
    cands = [c for c in camp if any(t in c for t in terms) and re.search(r'hero|chloe|elena|sully|cutter|talbot|marlowe|flynn|laz|navarro|eddie|charlie|ramses|npc|sol|pirate|guerro|roman|bedouin|schafer|jeff|agent|explorer|skel|winter|london|desert|young', c)]
    w('| %s | %d | %d | %s |' % (k, len(lst), sum(a + '.pak' in act4 for a in lst),
                               ', '.join(cands[:12]) + (' …(+%d)' % (len(cands) - 12) if len(cands) > 12 else '') or '-'))

# heads / kits / weapons
w('\n### MP weapons and anim actors\n')
mpw = sorted(a[:-4] for a in act3 if a.endswith('.pak') and re.search(r'-mp\.pak$|mp-[a-z0-9]+-(pistol|rifle)|all-(pistols|rifles)-mp', a))
w('| PS3 actor | PS4 |')
w('|---|---|')
for a in mpw:
    alt = a[:-3] if a.endswith('-mp') else None
    note = 'yes' if a + '.pak' in act4 else ('no (campaign `%s` exists)' % alt if alt and alt + '.pak' in act4 else 'no')
    w('| %s | %s |' % (a, note))

# ------------------------------------------------------------- c. taunts
w('\n## c. Taunts / emotes / MP animation sets\n')
anim = sorted(a for a in act3 if re.match(r'anim-(mp-|proto-multiplayer|proto-shield|proto-sprint|npc-multiplayer|npc-medium-mp|soldier-mp|npc-gestures)', a))
w('| PS3 actor33 entry | size | PS4 actor33 |')
w('|---|---|---|')
for a in anim:
    w('| %s | %d | %s |' % (a, act3[a], 'yes' if a in act4 else '**no**'))
mpstm = sorted(s for s in stm3 if re.search(r'mp-|multi', s))
w('\nPS3 animstream entries used by MP (%d): %s — PS4 animstream listing not staged (status unknown).\n' % (
    len(mpstm), ', '.join(mpstm)))
for dc in ['anim-net-player', 'net', 'net-anims', 'weapon-loadouts', 'mp-taunts', 'taunts', 'net-characters', 'net-unlocks', 'net-medals']:
    b3 = 'dc1/%s.bin' % dc in bin3
    b4 = '%s.bin' % dc in dc4
    if b3 or b4:
        w('- DC `%s.bin`: PS3 %s, PS4 %s' % (dc, 'yes' if b3 else 'no', 'yes' if b4 else 'no'))
mpdc3 = sorted(p for p in bin3 if p.startswith('dc1/ss-multiplayer/') and p.endswith('.bin'))
w('\nPS3 `dc1/ss-multiplayer/*.bin` scripts: %d (PS4 keeps level scripts inside `bin.psarc`; not staged).\n' % len(mpdc3))

# all MP actor coverage
w('\n## Totals over all MP/co-op levels\n')
am = sorted(a for a in all_mp_actors if a + '.pak' not in act4)
w('- actors referenced by MP/co-op levels: %d, missing on PS4: %d' % (len(all_mp_actors), len(am)))
pmm = sorted(p for p in all_mp_pms if p + '.bin' not in part4)
w('- particle modules referenced: %d, missing on PS4: %d (%s)' % (len(all_mp_pms), len(pmm), ', '.join(pmm)))
w('- sound banks referenced: %d (%s) — PS4 sound not staged' % (len(all_mp_banks), ', '.join(sorted(all_mp_banks))))
w('\nMissing MP-level actors: %s\n' % ', '.join(am))

print('\n'.join(out))
