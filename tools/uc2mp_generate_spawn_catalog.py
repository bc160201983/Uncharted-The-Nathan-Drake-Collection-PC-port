"""Generate an aligned C metadata catalogue from revalidated local source assets."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
from uc2mp_extract_spawns import extract, KNOWN, PS3_ELF_SHA256, require, sid


def float_literal(value):
    value = struct.unpack('<f', struct.pack('<f', value))[0]
    require(math.isfinite(value), 'Nonfinite generated float')
    text = format(value, '.9g')
    if '.' not in text and 'e' not in text:
        text += '.0'
    return text + 'f'


def render(catalogue):
    require(catalogue.get('metadata_only') is True, 'Expected metadata-only catalogue')
    require(catalogue.get('transform_contract', {}).get('sha256') == PS3_ELF_SHA256, 'Unexpected native transform contract')
    require([item['map'] for item in catalogue['maps']] == list(KNOWN), 'Unexpected map set/order')
    fingerprint = hashlib.sha256(json.dumps(catalogue, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    lines = [
        '/* Generated by tools/uc2mp_generate_spawn_catalog.py; do not edit poses by hand.',
        ' * Extracted metadata only. No PS3 PAK is loaded in the PC engine.',
        ' * Before spawning: native PC Level state7, ready80/keep40, origin+20 == zero.',
        f' * Validated metadata SHA256: {fingerprint}',
        ' */', '#ifndef UC2MP_EXTRACTED_SPAWN_CATALOG_H', '#define UC2MP_EXTRACTED_SPAWN_CATALOG_H',
        '#include <stddef.h>', '#include <stdint.h>', '#include <string.h>',
        '#ifdef __cplusplus', '#define UC2MP_SPAWN_ALIGN16 alignas(16)', '#else',
        '#define UC2MP_SPAWN_ALIGN16 _Alignas(16)', '#endif',
        'typedef struct Uc2mpExtractedSpawnPose {',
        '    uint32_t sid;', '    const char *name;',
        '    UC2MP_SPAWN_ALIGN16 float pose[8]; /* XYZ, zero W, quaternion XYZW */',
        '} Uc2mpExtractedSpawnPose;',
        'typedef struct Uc2mpExtractedSpawnMap {',
        '    const char *level_name;', '    uint32_t level_sid;',
        '    const Uc2mpExtractedSpawnPose *players;', '    size_t player_count;',
        '    const Uc2mpExtractedSpawnPose *cameras;', '    size_t camera_count;',
        '    const char *source_sha256;', '    const char *pc_reference_sha256;',
        '} Uc2mpExtractedSpawnMap;', '',
    ]
    for item in catalogue['maps']:
        name = item['map']
        expected = KNOWN[name]
        require(item['exact_common_transform_count'] == expected['common_count'], 'Insufficient matched coordinate anchors')
        require(all(item['sources'][key]['sha256'] == expected[key] for key in ('pc', 'ps3', 'wrapper')), 'Unverified source provenance')
        prefix = name.replace('-', '_')
        for kind, token, count in (('players', 'online-spawner-', expected['players']), ('cameras', 'camera-entity-', expected['cameras'])):
            entries = [row for row in item['entries'] if row['name'].startswith(token)]
            require(len(entries) == count, 'Unexpected entry count')
            require(len({row['sid'] for row in entries}) == count, 'Duplicate entry SID')
            lines.append(f'static const Uc2mpExtractedSpawnPose uc2mp_extracted_{prefix}_{kind}[] = {{')
            for row in entries:
                require(row['parent_null'] is True, 'Non-root pose requires native parent composition')
                require(int(row['sid'], 16) == sid(row['name']), 'Name/SID mismatch')
                pose = row['pc_pose32']
                require(len(pose) == 8 and pose[3] == 0, 'Invalid PC pose layout')
                require(pose[:3] == list(row['position_xyz']) and pose[4:] == list(row['quaternion']), 'Pose differs from extracted metadata')
                require(all(math.isfinite(value) for value in pose) and max(abs(value) for value in pose[:3]) < 100000, 'Invalid bounded pose')
                require(abs(sum(value * value for value in pose[4:]) - 1) < 1e-4, 'Quaternion must be unit length')
                lines.append('    {UINT32_C(0x' + row['sid'] + '), ' + json.dumps(row['name']) + ', {' + ', '.join(float_literal(value) for value in pose) + '}},')
            lines.append('};\n')
    lines.append('static const Uc2mpExtractedSpawnMap uc2mp_extracted_spawn_maps[] = {')
    for item in catalogue['maps']:
        name, prefix = item['map'], item['map'].replace('-', '_')
        expected = KNOWN[name]
        lines.append(f'    {{"{name}", UINT32_C(0x{sid(name):08x}), uc2mp_extracted_{prefix}_players, {expected["players"]}, uc2mp_extracted_{prefix}_cameras, {expected["cameras"]}, "{expected["wrapper"]}", "{expected["pc"]}"}},')
    lines.extend(['};', '',
        'static inline const Uc2mpExtractedSpawnMap *uc2mp_extracted_spawn_map(const char *name) {',
        '    if (!name) return NULL;',
        '    for (size_t i = 0; i < sizeof(uc2mp_extracted_spawn_maps) / sizeof(uc2mp_extracted_spawn_maps[0]); ++i)',
        '        if (strcmp(name, uc2mp_extracted_spawn_maps[i].level_name) == 0) return &uc2mp_extracted_spawn_maps[i];',
        '    return NULL;', '}', '',
        'static inline const Uc2mpExtractedSpawnPose *uc2mp_extracted_spawn_pose(const Uc2mpExtractedSpawnMap *map, uint32_t key) {',
        '    if (!map) return NULL;',
        '    for (size_t i = 0; i < map->player_count; ++i) if (map->players[i].sid == key) return &map->players[i];',
        '    for (size_t i = 0; i < map->camera_count; ++i) if (map->cameras[i].sid == key) return &map->cameras[i];',
        '    return NULL;', '}', '#undef UC2MP_SPAWN_ALIGN16', '#endif', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base', type=Path, required=True)
    parser.add_argument('--patch', type=Path)
    parser.add_argument('--ps3-cache', type=Path, required=True)
    parser.add_argument('--ps3-elf', type=Path, required=True)
    parser.add_argument('--ps3-pak22', type=Path, help='PS3 disc USRDIR/build/main/pak22.psarc')
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='Verify generated file without writing')
    args = parser.parse_args()
    output = args.out.resolve()
    roots = [args.base.resolve(), args.ps3_cache.resolve(), args.ps3_elf.resolve()]
    if args.patch:
        roots.append(args.patch.resolve())
    require(not any(output == root or output.is_relative_to(root) for root in roots), 'Cannot write generated metadata into original assets')
    source = render(extract(args.base, args.patch, args.ps3_cache, args.ps3_elf, args.ps3_pak22))
    if args.check:
        require(output.read_text(encoding='utf-8') == source, 'Generated header is stale')
    else:
        if output.exists():
            require(output.read_text(encoding='utf-8').startswith('/* Generated by tools/uc2mp_generate_spawn_catalog.py;'), 'Refusing to overwrite an unrelated header')
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(source, encoding='utf-8')
    print(json.dumps(dict(header=str(output), sha256=hashlib.sha256(source.encode()).hexdigest(), checked=args.check)))


if __name__ == '__main__':
    main()
